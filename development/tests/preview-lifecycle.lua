local T=PreviewTest local raw=T.exports local E=setmetatable({},{__index=raw}) local count=0
function E.Preview(...) return MX.unwrap(raw.Preview(...)) end
function E.ApplyPreview(...) return MX.unwrap(raw.ApplyPreview(...)) end
local function check(value,name) assert(value,name) count=count+1 end
local function entities() local n=0 for _ in pairs(T.entities) do n=n+1 end return n end
local function start(intent,model)
    E.PreviewIntent(7,'token',intent)
    local co=coroutine.create(function() return E.Preview(7,model,nil,{x=1,y=2,z=3,h=0},intent) end)
    local ok,action=coroutine.resume(co) check(ok and action=='load','load yields without spawning') return co
end
local applied={applied=true,capabilities={mods={},extras={},dimensions={length=4.0}}}
E.RegisterPreviewContext(7,'token','epoch',10007)
local automatic=coroutine.create(function()return E.Preview(7,'futo',nil,{x=1,y=2,z=3,h=0})end)
local autoOk,autoAction,autoData=coroutine.resume(automatic)
check(autoOk and autoAction=='load' and autoData.intent==nil,'automatic saved-car preview does not require a UI intent')
E.PreviewIntent(7,'token','replacement')
local autoDone,autoError=coroutine.resume(automatic,{loaded=true})
check(not autoDone and autoError.code=='OBSOLETE' and entities()==0,'automatic preview still respects server context cancellation')
local a=start('a','futo') E.PreviewIntent(7,'token','b')
local ok,err=coroutine.resume(a,{loaded=true})
check(not ok and err.code=='OBSOLETE' and entities()==0,'late load never publishes obsolete selection')
local b=start('b','elegy')
ok,err=coroutine.resume(b,{loaded=true}) check(ok and err=='apply' and entities()==1,'candidate tracked before yielding apply')
E.RemovePreview(7,false) check(entities()==0,'closing removes in-flight candidate')
ok,err=coroutine.resume(b,applied) check(ok and err=='previewCleared','obsolete completion verifies removal')
ok,err=coroutine.resume(b,{cleared=true}) check(not ok and err.code=='OBSOLETE' and entities()==0,'closed context cannot publish late callback')
E.RegisterPreviewContext(7,'token','epoch',10007)
local c=start('c','futo') coroutine.resume(c,{loaded=true})
ok,err=coroutine.resume(c,applied) check(ok and err.model=='futo' and entities()==1,'one committed presentation')
local original=E.CurrentPreview(7).id local before=E.PreviewMetrics()
E.PreviewIntent(7,'token','same')
local identical=E.Preview(7,'futo',nil,{x=1,y=2,z=3,h=0},'same')
check(identical.id==original and E.PreviewMetrics().created==before.created and E.PreviewMetrics().loaded==before.loaded,'identical request does not load or recreate')
local properties=VehicleProperties.defaults() properties.primary=12
E.PreviewIntent(7,'token','paint')
local paint=coroutine.create(function() return E.Preview(7,'futo',properties,{x=1,y=2,z=3,h=0},'paint') end)
ok,err=coroutine.resume(paint) check(ok and err=='apply','same model applies configuration without loading')
ok,err=coroutine.resume(paint,applied)
check(ok and err.id==original and err.properties.primary==12 and entities()==1,'same model keeps entity and new properties')
check(E.PreviewMetrics().created==before.created and E.PreviewMetrics().removed==before.removed,'configuration switch creates and removes nothing')
local d=start('d','elegy2')
ok,err=coroutine.resume(d,{loaded=true}) check(ok and err=='previewCleared' and entities()==0,'delete observed before replacement creation')
ok,err=coroutine.resume(d,{cleared=true}) check(ok and err=='apply' and entities()==1,'new candidate only after clear ack')
ok,err=coroutine.resume(d,applied) check(ok and err.model=='elegy2' and entities()==1,'replacement leaves exactly one')
local f=start('f','sultan') ok,err=coroutine.resume(f,{loaded=false})
check(not ok and err.code=='ASSET' and entities()==1 and E.CurrentPreview(7).model=='elegy2','failed model load preserves usable previous presentation')
local g=start('g','blista') coroutine.resume(g,{loaded=true})
E.PreviewIntent(7,'token','h') ok,err=coroutine.resume(g,{cleared=true})
check(not ok and err.code=='OBSOLETE' and entities()==0,'intent revalidated after deletion ack')
local h=start('h','futo') coroutine.resume(h,{loaded=true}) coroutine.resume(h,applied)
check(entities()==1 and E.CurrentPreview(7).model=='futo','latest choice recovers scene')
local cos=coroutine.create(function() return E.ApplyPreview(7,VehicleProperties.defaults()) end)
coroutine.resume(cos) E.PreviewIntent(7,'token','i') ok,err=coroutine.resume(cos,applied)
check(not ok and err.code=='OBSOLETE','late cosmetics cannot confirm a superseded entity')
check(not E.PreviewIntent(7,'wrong-token','j'),'other context cannot cancel current preview')
source=7 T.events.playerDropped() check(entities()==0,'disconnect removes only tracked presentations')
check(E.CurrentPreview(7)==nil,'removed handles are not returned')
E.RegisterPreviewContext(7,'token','epoch',10007)
local reuse=start('reuse','futo') coroutine.resume(reuse,{loaded=true}) local _,published=coroutine.resume(reuse,applied)
T.entities[published.net]={model='unmanaged',state={}}
E.RemovePreview(7,false)
check(entities()==1 and T.entities[published.net].model=='unmanaged','reused handle belonging to another entity is never deleted')
check(E.CurrentPreview(7)==nil,'reused handle is not an active presentation')
print(count..' verificações do controlador real de prévias com natives simuladas (não é validação FiveM)')
E.RegisterPreviewContext(7,'token','epoch',10007)
local requested=VehicleProperties.defaults() requested.stance=VehicleStanceRules.defaults() requested.stance.wheelSize=1.1
E.PreviewIntent(7,'token','limited')
local normalized=coroutine.create(function()return E.Preview(7,'futo',requested,{x=1,y=2,z=3,h=0},'limited')end)
assert(coroutine.resume(normalized)) assert(coroutine.resume(normalized,{loaded=true}))
local effective=VehicleStanceRules.defaults()
local done,result=coroutine.resume(normalized,{applied=true,capabilities={},stance={value=effective,warning='Diâmetro indisponível'}})
assert(done and result.properties.stance.wheelSize==1 and E.CurrentPreview(7).properties.stance.wheelSize==1,'real preview stores/publishes acknowledged stance, not refused factor')
local update=coroutine.create(function()return E.ApplyPreview(7,requested)end)
assert(coroutine.resume(update))
done,result=coroutine.resume(update,{applied=true,capabilities={},stance={value=effective}})
assert(done and E.CurrentPreview(7).properties.stance.wheelSize==1,'cosmetic preview also stores the effective stance for subsequent persistence')
print('Stance preview normalization: candidate and cosmetic ACKs preserve the effective dimension (adapters).')
